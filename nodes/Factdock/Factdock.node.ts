export class Factdock implements INodeType {
	description: INodeTypeDescription = {
		displayName: 'Factdock',
		name: 'factdock',
		icon: { light: 'file:../../icons/factdock.svg', dark: 'file:../../icons/factdock.dark.svg' },
		group: ['transform'],
		version: 1,
		subtitle: '={{$parameter["operation"] + ": " + $parameter["resource"]}}',
		description:
			'Search primary sources worldwide, each country in its own language: web, academic papers, patents, companies, trade rules, infrastructure, finance and news',
		defaults: { name: 'Factdock' },
		usableAsTool: true,
		inputs: [NodeConnectionTypes.Main],
		outputs: [NodeConnectionTypes.Main],
		credentials: [{ name: 'factdockApi', required: true }],
		requestDefaults: {
			baseURL: 'https://data.fact-dock.com',
			headers: { Accept: 'application/json', 'Content-Type': 'application/json' },
			// Country web searches, patent searches and company reports can take close to three minutes.
			timeout: 200000,
		},
		properties: [
			{
				displayName: 'Resource',
				name: 'resource',
				type: 'options',
				noDataExpression: true,
				options: [
					{ name: 'Company', value: 'company' },
					{ name: 'Finance', value: 'finance' },
					{ name: 'Government', value: 'government' },
					{ name: 'Insight', value: 'insights' },
					{ name: 'Search', value: 'search' },
					{ name: 'Trade', value: 'trade' },
				],
				default: 'search',
			},
			...operations,
			...fields,
		],
	};
}
